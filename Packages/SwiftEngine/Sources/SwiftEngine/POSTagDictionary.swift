    /// Resolves primary and secondary POS tags for a given word.
    @inline(__always)
    public static func resolve(word: String) -> (primary: POSTag, secondary: POSTag) {
        if let exact = lexicon[word] {
            return exact
        }

        let count = word.count
        guard count >= 2 else {
            return (.none, .none)
        }

        guard let lastChar = word.last else {
            return (.none, .none)
        }

        if wearableSuffixes.contains(lastChar) {
            return (.naWearable, .none)
        }
        if generalItemSuffixes.contains(lastChar) {
            return (.naGeneral, .none)
        }
        if locativeSuffixes.contains(lastChar) {
            return (.nc, .none)
        }
        if temporalSuffixes.contains(lastChar) {
            return (.nd, .none)
        }

        // Multi-character words default to common nouns unless matched otherwise
        return (.naGeneral, .none)
    }
